-- 용돈 규칙. 시드 규칙에는 용돈이 없어서 `길동 용돈` · `철수 용돈` 같은 행이
-- 거래 유형만 보는 `자동이체` 포괄 규칙(priority 90)에 걸려 고정비로 분류된다.
-- 용돈은 고정비가 아니라 고정지출1(저축 · 용돈 · 주거비) 칸에 들어가야 한다.
--
-- ── priority 75 를 고른 이유 ──────────────────────────────────────────────
--
-- 시드 규칙의 사다리는 이렇게 나뉜다.
--
--   10~70  적요를 보는 구체적인 규칙(계좌 간 이동 · 카드대금 · 대출이자 ·
--          연금/IRP/ISA · 코인적립 · 통장이자)
--   80~90  적요를 보지 않고 거래 유형만 보는 포괄 규칙(`.*`)
--
-- 75 는 그 둘 사이의 유일한 빈칸이다.
--   * 90(자동이체) · 80(이자입금) 보다 **앞선다** — 용돈 행이 포괄 규칙에
--     먹히기 전에 잡힌다. 이것이 이 마이그레이션의 목적이다.
--   * 10~70 보다 **뒤에 온다** — 적요에 `용돈` 과 `비상금 계좌` 가 함께 들어간
--     행이 생겨도 계좌 간 이동 판정이 그대로 이긴다. 즉 기존 구체 규칙을
--     하나도 가리지 않는다.
-- 10 단위 사다리를 유지하면서 중간에 끼우려면 5 단위가 필요해 75 가 됐다.
-- (같은 priority 를 쓰면 id 오름차순 타이브레이커에 의존하게 되는데, 나중에
--  규칙을 지우고 다시 넣으면 id 가 바뀌어 순서가 흔들린다.)
--
-- ── 패턴과 sign 가드 ──────────────────────────────────────────────────────
--
-- 패턴은 `용돈` 부분 문자열 그대로다. 표기가 `길동 용돈` · `철수 용돈` 처럼
-- 이름+용도라서 이름 쪽을 패턴에 넣을 수 없고(개인 라벨을 스키마에 박지
-- 않는다), 앞에 공백을 강제하면 `용돈이체` 처럼 붙여 쓴 표기를 놓친다.
--
-- sign = -1 가드를 **넣는다.** 카드대금 규칙에서 `전자카드비` 라는 +입금이
-- 카드대금으로 새는 것을 막은 것과 같은 이유다. 용돈은 정의상 나가는 돈이고,
-- 적요에 `용돈` 이 들어간 +입금(받은 용돈 · 반환)은 지출 분류에 들어가서는
-- 안 된다. 실제 용돈 행은 전부 출금이라 이 가드로 놓치는 행은 없다.
