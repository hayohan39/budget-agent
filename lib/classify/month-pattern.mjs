// 월마다 바뀌는 적요 토큰(`08월` · `9월` · `12월` …)을 지운 보조 키.
//
// ── 왜 필요한가 ───────────────────────────────────────────────────────────
//
// "코웨이08월렌탈" 같은 고정비는 다음 달이면 "코웨이09월렌탈"로 적요가 바뀐다.
// merchant_map 의 키는 정규화한 적요 원문이라, 이런 적요는 달마다 새 키가 되어
// "앞으로도"로 저장한 매핑이 다음 달에는 걸리지 않는다(engine.mjs 의 우선순위
// 1번이 정확히 일치해야 걸린다). 사용자 요청: "코웨이08월렌탈의 경우 월별로
// 코웨이09월렌탈, 코웨이10월렌탈 바뀌게 되는 고정비야."
//
// 이 파일은 그 문제를 **정규식을 사용자에게 노출하지 않고** 푼다. `/classify`
// 는 정규식 편집기를 두지 않는다(PLAN.md). 대신 코드가 고정으로 갖는 "월 토큰"
// 정규화 함수 하나를 두고, 사람은 체크박스로만 그 정규화를 켠다
// (lib/classify/manual.mjs 의 `applyClassification`, app/classify/forms.tsx).
//
// ── 무엇을 지우는가 ───────────────────────────────────────────────────────
//
// 1~2자리 숫자 바로 뒤에 `월` 이 붙은 토큰(`08월` · `9월` · `12월`)만 지운다.
// `월` 앞에 숫자가 없으면(`월세` · `이번달`) 건드리지 않는다 — 숫자가 없는
// `월` 은 "이 적요가 달마다 바뀐다"는 신호가 아니라 그냥 단어의 일부다.
//
// ── ReDoS 안전성 ──────────────────────────────────────────────────────────
//
// 이 파일이 쓰는 정규식은 `\d{1,2}월` 한 모양뿐이다(판정용 · 치환용 두 상수로
// 나눈 것은 `g` 플래그의 `lastIndex` 상태를 없애기 위해서일 뿐, 패턴 자체는
// 같다).
//   - 수량자는 `{1,2}` 하나뿐이고 유한하다. 중첩된 그룹도, 그룹에 붙은
//     수량자도 없다(pattern.mjs 가 막는 "유한 반복의 곱" 문제 자체가 없다).
//   - 교대(`|`)가 없다 — `(a|a)*` 류의 모호성이 애초에 생기지 않는다.
//   - 이 정규식이 입력을 훑는 데 걸리는 시간은 입력 길이에 **선형**이다.
//     한 글자를 보고 숫자인지 · `월` 인지만 판정하며, 실패해도 되짚어 볼
//     경로가 없다(역추적할 대상이 없다). pattern.mjs 의 "무한 수량자를 아예
//     받지 않으면 역추적 경로 수가 구조적으로 묶인다"는 논리와 같은 이유로,
//     이 정규식은 애초에 역추적이 필요한 모양이 아니다.
//   - 패턴이 코드에 고정되어 있다 — DB · 사용자 입력에서 오지 않는다. 그래도
//     "고정된 패턴이니 안전하다"에 기대지 않고 위 두 가지로 선형성을 보장한다.
//
// console 호출이 이 파일에 없다.

/**
 * 1~2자리 숫자 + `월`. 있는지만 보는 판정용(플래그 없음) — 전역 플래그가
 * `lastIndex` 상태를 남겨 호출마다 결과가 달라지는 일을 아예 만들지 않는다
 * (pattern.mjs 가 분류 규칙에 `g` 플래그를 쓰지 않는 것과 같은 이유).
 */
const HAS_MONTH_TOKEN = /\d{1,2}월/;

/** 위와 같은 모양이지만 전역 플래그로 지운다 — 이 상수는 `replace()` 에만 쓴다. */
const MONTH_TOKEN = /\d{1,2}월/g;

/**
 * `normalizeDescription` 을 거친 적요에서 월 토큰을 지운 보조 키를 만든다.
 *
 * 월 토큰이 하나도 없으면 `null` 을 돌려준다 — "지워도 바뀌지 않았다"(원문
 * 그대로)가 아니라 "이 적요는 월마다 바뀌는 모양이 아니다"를 호출자가
 * 구분할 수 있어야 하기 때문이다(engine.mjs 의 폴백 조회는 원본 키와 같은
 * 값으로 다시 조회하면 안 되고, /classify 의 체크박스는 토큰이 없으면 저장
 * 자체를 거부해야 한다).
 *
 * 지운 뒤 남는 글자가 없거나 공백뿐이면 역시 `null` 이다 — 빈 매핑 키를
 * merchant_map 에 저장할 수 없고(CHECK), 빈 키로는 애초에 아무 적요도
 * 찾을 수 없다.
 *
 * @param {unknown} description 정규화한 적요(공백은 이미 하나로 눌려 있다고
 *   가정하지만, 이 함수는 그 가정이 깨져도 스스로 공백을 다시 정리한다)
 * @returns {string | null}
 */
export function stripMonthToken(description) {
  if (typeof description !== 'string') return null;
  if (!HAS_MONTH_TOKEN.test(description)) return null;

  const stripped = description
    .replace(MONTH_TOKEN, '')
    .replace(/\s+/gu, ' ')
    .trim();

  return stripped === '' ? null : stripped;
}
